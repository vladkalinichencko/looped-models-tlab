#!/usr/bin/env bash
# Базовая кривая задания: одни и те же параметры и токены, разное число лупов.
#
# Бюджет 25M токенов вместо разрешённых 100M — стоимость линейна по числу лупов, и
# полный свип на 100M это порядка 36 часов только на нём (tmp/bench.txt). Бюджет
# одинаков у всех вариантов, поэтому сравнение честное; финал гоняем на 100M.
#
# --grad-checkpoint обязателен начиная примерно с четырёх лупов: без него граф держит
# все применения блока, при 16 лупах это 64 штуки и порядка 14 ГБ активаций. На лосс
# не влияет (проверено, совпадение до 1e-5), стоит около 30% времени.
#
#   ./run_sweep.sh                    # 2 4 8 16 (1 уже посчитан)
#   ./run_sweep.sh 1 2 4              # только эти
#   TOKENS=100000000 ./run_sweep.sh   # полный бюджет, для A100
set -euo pipefail
cd "$(dirname "$0")"

TOKENS="${TOKENS:-25000000}"
LOOPS=("$@")
[ ${#LOOPS[@]} -eq 0 ] && LOOPS=(2 4 8 16)

for n in "${LOOPS[@]}"; do
  .venv/bin/python -u train.py --tag "loops${n}" --n-loops "$n" --tokens "$TOKENS" \
    --grad-checkpoint --diag-every 250 --eval-every 250
done
